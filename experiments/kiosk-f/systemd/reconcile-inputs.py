#!/usr/bin/env python3
"""Refresh configured stable evdev mappings in one native runtime Quadlet.

No config commits, saved configuration edits or additional device grants. Only
an active kiosk is restarted, after debouncing and under the native commit lock.
Absent devices are left pending: this does not implement boot without devices.
"""
import argparse
import json
import os
from pathlib import Path
import re
import stat
import subprocess
import tempfile
import time

EVENT = re.compile(r'/dev/input/event[0-9]+')
STABLE = re.compile(r'/dev/input/by-(?:id|path)/[^/\s:%]+')


def resolve_device(source):
    path = Path(source).resolve(strict=True)
    if not EVENT.fullmatch(str(path)):
        raise ValueError('Stable input path does not resolve to an evdev node')
    info = path.stat()
    if not stat.S_ISCHR(info.st_mode) or os.major(info.st_rdev) != 13:
        raise ValueError('Input source is not an input character device')
    return str(path)


def plan(text, resolve=resolve_device):
    if not text.startswith('### Autogenerated by container.py ###'):
        raise ValueError('Not a native VyOS container Quadlet')
    if not re.search(r'^Environment=KIOSK_ROTATION=', text, re.M):
        raise ValueError('Not a native kiosk container')
    lines, expected, destinations = [], [], set()
    for line in text.splitlines(keepends=True):
        if line.startswith('AddDevice='):
            fields = line.strip().split('=', 1)[1].split(':')
            if len(fields) not in (2, 3):
                raise ValueError('Unsupported device mapping')
            source, destination = fields[:2]
            if STABLE.fullmatch(source) and EVENT.fullmatch(destination):
                current = resolve(source)  # Fail closed if any selected device is absent.
                expected.append((current, current))
                fields[1] = current
                destination = current
                line = 'AddDevice=' + ':'.join(fields) + '\n'
            if destination in destinations:
                raise ValueError('Input remap conflicts with another device destination')
            destinations.add(destination)
        lines.append(line)
    return ''.join(lines), expected


def run(args, timeout=10):
    return subprocess.run(args, capture_output=True, text=True, check=True, timeout=timeout).stdout


def active(name):
    return subprocess.run(['systemctl', 'is-active', '--quiet', f'vyos-container-{name}.service'],
                          timeout=5).returncode == 0


def snapshot(name):
    path = Path('/run/containers/systemd') / f'vyos-container-{name}.container'
    if path.is_symlink():
        raise ValueError('Refusing symlink Quadlet')
    text = path.read_text()
    updated, expected = plan(text)
    item = json.loads(run(['podman', 'inspect', name]))[0]
    if not item.get('State', {}).get('Running'):
        return None
    mappings = {(d['PathOnHost'], d['PathInContainer']) for d in item['HostConfig'].get('Devices', [])}
    if text == updated and all(pair in mappings for pair in expected):
        return None
    return path, text, updated, tuple(expected), item['Id']


def atomic(path, text):
    mode = stat.S_IMODE(path.stat().st_mode)
    fd, name = tempfile.mkstemp(dir=path.parent, prefix='.kiosk-input-')
    try:
        with os.fdopen(fd, 'w') as stream:
            stream.write(text)
            stream.flush()
            os.fsync(stream.fileno())
            os.fchmod(stream.fileno(), mode)
        os.replace(name, path)
    finally:
        if os.path.exists(name):
            os.unlink(name)


def apply(name, observed):
    from vyos.utils.commit import acquire_commit_lock_file, release_commit_lock_file
    lock, _ = acquire_commit_lock_file()
    if lock is None:
        return False
    try:
        if not active(name) or snapshot(name) != observed:
            return False  # Config, USB or container changed while debouncing.
        path, old, updated, expected, _ = observed
        atomic(path, updated)
        try:
            run(['systemctl', 'daemon-reload'], timeout=30)
            # Recheck physical resolution before stopping a working desktop.
            if plan(updated)[1] != list(expected):
                raise ValueError('USB mapping changed before restart')
            run(['systemctl', 'restart', f'vyos-container-{name}.service'], timeout=90)
        except (OSError, ValueError, subprocess.SubprocessError):
            # Restore only our own runtime edit, never overwrite a newer native one.
            if path.read_text() == updated:
                atomic(path, old)
                run(['systemctl', 'daemon-reload'], timeout=30)
            raise
        print(f'Kiosk {name}: refreshed configured USB event mappings and restarted container', flush=True)
        return True
    finally:
        release_commit_lock_file(lock)


def watch(name, once=False):
    previous, since, cooldown, last_error = None, 0, 0, None
    while True:
        try:
            observed = snapshot(name) if active(name) else None
            if once:
                print(json.dumps({'change_required': observed is not None,
                                  'mappings': observed[3] if observed else []}))
                return  # --check never writes/restarts.
            if observed != previous:
                previous, since = observed, time.monotonic()
            if observed and time.monotonic() - since >= 3 and time.monotonic() >= cooldown:
                cooldown = time.monotonic() + 30
                apply(name, observed)
                previous = None
            last_error = None
        except (OSError, ValueError, KeyError, IndexError, subprocess.SubprocessError) as error:
            previous = None
            message = str(error)
            if message != last_error:
                print(f'Kiosk input reconciliation pending: {message}', flush=True)
                last_error = message
            if once:
                raise
        time.sleep(2)


if __name__ == '__main__':
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument('container')
    parser.add_argument('--check', action='store_true')
    args = parser.parse_args()
    if not re.fullmatch(r'[A-Za-z0-9][A-Za-z0-9_.-]{0,62}', args.container):
        parser.error('Invalid container name')
    watch(args.container, args.check)
