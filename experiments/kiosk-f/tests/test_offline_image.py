import importlib.util
import hashlib
import json
from pathlib import Path
from types import SimpleNamespace
import tempfile
import unittest

BASE = Path(__file__).resolve().parents[1] / 'image'


def load(name):
    spec = importlib.util.spec_from_file_location(name, BASE / (name + '.py'))
    module = importlib.util.module_from_spec(spec)
    spec.loader.exec_module(module)
    return module


class OfflineImage(unittest.TestCase):
    def test_stage_preserves_config_and_state(self):
        with tempfile.TemporaryDirectory() as tmp:
            root = Path(tmp) / 'root'; root.mkdir()
            artifacts = Path(tmp) / 'artifacts'; artifacts.mkdir()
            config = root / 'config/config.boot'; config.parent.mkdir(); config.write_bytes(b'customer config')
            state = root / 'config/kiosk/state.json'; state.parent.mkdir(); state.write_bytes(b'customer settings')
            (artifacts / 'runtime.tar').write_bytes(b'archive')
            (artifacts / 'runtime.json').write_text(json.dumps({'archive_sha256': hashlib.sha256(b'archive').hexdigest()}))
            load('stage-runtime').stage(root, artifacts)
            load('stage-runtime').stage(root, artifacts)
            self.assertEqual(config.read_bytes(), b'customer config')
            self.assertEqual(state.read_bytes(), b'customer settings')
            self.assertTrue((root / 'etc/systemd/system/vyos.target.wants/vyarm-kiosk-runtime.service').is_symlink())

    def test_import_waits_for_first_boot_partition_growth(self):
        unit = (BASE / 'vyarm-kiosk-runtime.service').read_text()
        self.assertIn('Wants=vyos-arm64-grow-persistence.service', unit)
        after = next(line for line in unit.splitlines() if line.startswith('After='))
        self.assertIn('vyos-arm64-grow-persistence.service', after.split())
        self.assertIn('Before=vyos-router.service', unit)

    def test_existing_tag_collision_never_loads_or_retags(self):
        with tempfile.TemporaryDirectory() as tmp:
            root = Path(tmp)
            (root / 'runtime.json').write_text(json.dumps({'image': 'localhost/vyarm-kiosk:version', 'image_id': 'a'*64}))
            calls = []
            def run(args, **kwargs):
                calls.append(args)
                return SimpleNamespace(returncode=0, stdout='b'*64)
            with self.assertRaises(ValueError):
                load('import-runtime').install(root, run)
            self.assertFalse(any('load' in call or 'tag' in call for call in calls))

    def test_generator_scopes_native_kiosk_only(self):
        with tempfile.TemporaryDirectory() as tmp:
            src = Path(tmp) / 'src'; src.mkdir()
            out = Path(tmp) / 'out'
            prefix = '### Autogenerated by container.py ###\n'
            (src / 'vyos-container-signage.container').write_text(prefix+'Environment=KIOSK_ROTATION=90\n')
            (src / 'vyos-container-other.container').write_text(prefix+'Image=other\n')
            load('kiosk-generator').generate(src, out)
            self.assertTrue((out / 'vyos-kiosk-inputs-signage.service').exists())
            self.assertFalse((out / 'vyos-kiosk-inputs-other.service').exists())


if __name__ == '__main__':
    unittest.main()
