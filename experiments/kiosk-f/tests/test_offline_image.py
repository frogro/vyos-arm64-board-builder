import importlib.util
import hashlib
import json
from pathlib import Path
from types import SimpleNamespace
import tempfile
import unittest

BASE = Path(__file__).resolve().parents[1] / 'image'


def load(name):
    spec = importlib.util.spec_from_file_location(name, BASE / (name + '.py'))
    module = importlib.util.module_from_spec(spec)
    spec.loader.exec_module(module)
    return module


class OfflineImage(unittest.TestCase):
    def test_stage_preserves_config_and_state(self):
        with tempfile.TemporaryDirectory() as tmp:
            root = Path(tmp) / 'root'; root.mkdir()
            artifacts = Path(tmp) / 'artifacts'; artifacts.mkdir()
            config = root / 'config/config.boot'; config.parent.mkdir(); config.write_bytes(b'customer config')
            state = root / 'config/kiosk/state.json'; state.parent.mkdir(); state.write_bytes(b'customer settings')
            (artifacts / 'runtime.tar').write_bytes(b'archive')
            (artifacts / 'runtime.json').write_text(json.dumps({'archive_sha256': hashlib.sha256(b'archive').hexdigest()}))
            load('stage-runtime').stage(root, artifacts)
            load('stage-runtime').stage(root, artifacts)
            self.assertTrue((root / 'usr/local/sbin/vyarm-kiosk-setup').is_file())
            self.assertEqual(config.read_bytes(), b'customer config')
            self.assertEqual(state.read_bytes(), b'customer settings')
            self.assertTrue((root / 'etc/systemd/system/vyos.target.wants/vyarm-kiosk-runtime.service').is_symlink())

    def test_setup_commands_have_complete_standard_devices_and_safe_defaults(self):
        lines = load('setup-kiosk').commands('kiosk', 'localhost/vyarm-kiosk:test',
                   '/dev/dri/card1', [('/dev/input/by-id/usb-touch-event', '/dev/input/event7')])
        text = '\n'.join(lines)
        self.assertIn('device display source /dev/dri/card1', text)
        self.assertIn('device display destination /dev/dri/card0', text)
        self.assertIn('device input-0 source /dev/input/by-id/usb-touch-event', text)
        self.assertIn('volume state source /config/kiosk/state', text)
        self.assertIn('kiosk rotation 0', text)
        self.assertIn('kiosk video-decode software', text)
        self.assertNotIn('remote access enabled', text)
        with self.assertRaises(ValueError):
            load('setup-kiosk').commands('../bad', 'localhost/vyarm-kiosk:test', '/dev/dri/card0', [])

    def test_optional_encoder_and_playback_devices_without_remote_or_microphone(self):
        setup = load('setup-kiosk')
        text = '\n'.join(setup.commands('kiosk', 'localhost/vyarm-kiosk:test', '/dev/dri/card0', [],
            encoder_devices=['/dev/mpp_service','/dev/dma_heap/system'],
            audio_devices=['/dev/snd/controlC1','/dev/snd/pcmC1D0p'],
            mpp_compatible='/sys/firmware/devicetree/base/compatible'))
        self.assertIn('device encoder-0 source /dev/mpp_service', text)
        self.assertIn('volume mpp-compatible destination /run/mpp/compatible', text)
        self.assertIn('volume mpp-compatible mode ro', text)
        self.assertIn('device audio-1 source /dev/snd/pcmC1D0p', text)
        self.assertNotIn('remote access enabled', text)
        with self.assertRaises(ValueError):
            setup.commands('kiosk','localhost/vyarm-kiosk:test','/dev/dri/card0',[],audio_devices=['/dev/snd/pcmC0D0c'])

    def test_import_waits_for_first_boot_partition_growth(self):
        unit = (BASE / 'vyarm-kiosk-runtime.service').read_text()
        self.assertIn('Wants=vyos-arm64-grow-persistence.service', unit)
        after = next(line for line in unit.splitlines() if line.startswith('After='))
        self.assertIn('vyos-arm64-grow-persistence.service', after.split())
        self.assertIn('Before=vyos-router.service', unit)

    def test_existing_tag_collision_never_loads_or_retags(self):
        with tempfile.TemporaryDirectory() as tmp:
            root = Path(tmp)
            (root / 'runtime.json').write_text(json.dumps({'image': 'localhost/vyarm-kiosk:version', 'image_id': 'a'*64}))
            calls = []
            def run(args, **kwargs):
                calls.append(args)
                return SimpleNamespace(returncode=0, stdout='b'*64)
            with self.assertRaises(ValueError):
                load('import-runtime').install(root, run)
            self.assertFalse(any('load' in call or 'tag' in call for call in calls))

    def test_generator_scopes_native_kiosk_only(self):
        with tempfile.TemporaryDirectory() as tmp:
            src = Path(tmp) / 'src'; src.mkdir()
            out = Path(tmp) / 'out'
            prefix = '### Autogenerated by container.py ###\n'
            (src / 'vyos-container-signage.container').write_text(prefix+'Environment=KIOSK_ROTATION=90\n')
            (src / 'vyos-container-other.container').write_text(prefix+'Image=other\n')
            load('kiosk-generator').generate(src, out)
            self.assertTrue((out / 'vyos-kiosk-inputs-signage.service').exists())
            self.assertFalse((out / 'vyos-kiosk-inputs-other.service').exists())
            for prefix in ('vyos-kiosk-inputs-', 'vyos-kiosk-sunshine-inputs-'):
                text = (out / (prefix+'signage.service')).read_text()
                self.assertIn('BindsTo=vyos-container-signage.service', text)
                self.assertIn('PartOf=vyos-container-signage.service', text)
                self.assertIn('After=vyos-container-signage.service', text)


if __name__ == '__main__':
    unittest.main()
