import importlib.util
from pathlib import Path
import subprocess
import sys
import tempfile
import types
import unittest
from unittest.mock import patch

spec = importlib.util.spec_from_file_location('reconcile', Path(__file__).resolve().parents[1] / 'systemd/reconcile-inputs.py')
r = importlib.util.module_from_spec(spec)
spec.loader.exec_module(r)
HEADER = '### Autogenerated by container.py ###\n[Container]\nEnvironment=KIOSK_ROTATION="90"\n'


class InputReconcileTests(unittest.TestCase):
    def test_shifted_numbers_preserve_everything_except_selected_destinations(self):
        text = HEADER + ('AddDevice=/dev/input/by-id/keyboard:/dev/input/event0\n'
                         'AddDevice=/dev/input/by-path/touch:/dev/input/event4\n'
                         'AddDevice=/dev/dri/card0:/dev/dri/card0\n'
                         'PublishPort=127.0.0.1:47990:47990/tcp\nVolume=/state:/state\n')
        resolve = {'/dev/input/by-id/keyboard': '/dev/input/event4',
                   '/dev/input/by-path/touch': '/dev/input/event0'}.__getitem__
        updated, pairs = r.plan(text, resolve)
        self.assertEqual(updated, text.replace('keyboard:/dev/input/event0', 'keyboard:/dev/input/event4')
                                     .replace('touch:/dev/input/event4', 'touch:/dev/input/event0'))
        self.assertEqual(pairs, [('/dev/input/event4', '/dev/input/event4'), ('/dev/input/event0', '/dev/input/event0')])
        self.assertEqual(r.plan(updated, resolve)[0], updated)

    def test_missing_input_does_not_produce_partial_update(self):
        with self.assertRaises(FileNotFoundError):
            r.plan(HEADER+'AddDevice=/dev/input/by-id/touch:/dev/input/event4\n',
                   lambda _: (_ for _ in ()).throw(FileNotFoundError()))

    def test_conflicting_destination_is_rejected(self):
        with self.assertRaises(ValueError):
            r.plan(HEADER+'AddDevice=/dev/input/by-id/touch:/dev/input/event4\nAddDevice=/dev/input/event0:/dev/input/event0\n',
                   lambda _: '/dev/input/event0')

    def test_only_native_kiosk_and_stable_input_mappings(self):
        with self.assertRaises(ValueError):
            r.plan('[Container]\n')
        text = HEADER+'AddDevice=/dev/input/event4:/dev/input/event4\n'
        self.assertEqual(r.plan(text), (text, []))
        with self.assertRaises(ValueError):
            r.plan(HEADER.replace('KIOSK_ROTATION', 'OTHER'))

    def test_changed_snapshot_never_restarts(self):
        module = types.SimpleNamespace(acquire_commit_lock_file=lambda: ('lock',''),
                                       release_commit_lock_file=lambda _: None)
        with patch.dict(sys.modules, {'vyos.utils.commit': module}), patch.object(r, 'active', return_value=True), \
                patch.object(r, 'snapshot', return_value=None), patch.object(r, 'run') as run:
            self.assertFalse(r.apply('screen', ('stale',)))
            run.assert_not_called()

    def test_commit_lock_busy_does_not_touch_runtime(self):
        module = types.SimpleNamespace(acquire_commit_lock_file=lambda: (None,'busy'),
                                       release_commit_lock_file=lambda _: None)
        with patch.dict(sys.modules, {'vyos.utils.commit': module}), patch.object(r, 'snapshot') as snapshot:
            self.assertFalse(r.apply('screen', None))
            snapshot.assert_not_called()

    def test_restart_failure_restores_own_runtime_edit(self):
        module = types.SimpleNamespace(acquire_commit_lock_file=lambda: ('lock',''),
                                       release_commit_lock_file=lambda _: None)
        with tempfile.TemporaryDirectory() as tmp:
            path = Path(tmp)/'screen.container'
            path.write_text('old')
            observed = (path, 'old', 'new', (), 'id')
            with patch.dict(sys.modules, {'vyos.utils.commit': module}), patch.object(r, 'active', return_value=True), \
                    patch.object(r, 'snapshot', return_value=observed), patch.object(r, 'plan', return_value=('new', [])), \
                    patch.object(r, 'run', side_effect=['', subprocess.CalledProcessError(1,'systemctl'), '']):
                with self.assertRaises(subprocess.CalledProcessError):
                    r.apply('screen', observed)
            self.assertEqual(path.read_text(), 'old')


if __name__ == '__main__':
    unittest.main()
